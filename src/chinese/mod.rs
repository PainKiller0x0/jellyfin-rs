use regex::Regex;
use std::sync::LazyLock;

// Compiled regexes for language detection
#[allow(dead_code)]
static RE_CHINESE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"[一-鿿]").unwrap());
#[allow(dead_code)]
static RE_JAPANESE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"[぀-ヿ]").unwrap());
#[allow(dead_code)]
static RE_KOREAN: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"[가-힣]").unwrap());
#[allow(dead_code)]
static RE_ENGLISH: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^[\x00-\x7F]+$").unwrap());

// Default episode name patterns
#[allow(dead_code)]
static RE_DEFAULT_EPISODE_EN: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^Episode\s*\d+$").unwrap());
#[allow(dead_code)]
static RE_DEFAULT_EPISODE_ZH: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^第\s*\d+\s*集$").unwrap());
#[allow(dead_code)]
static RE_DEFAULT_EPISODE_JA: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^第\s*\d+\s*話$").unwrap());

// Season/episode pattern for name cleaning
#[allow(dead_code)]
static RE_SEASON_EPISODE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\.[Ss]\d{1,2}[EeXx]\d{1,3}|\.第\d+集|\.第\d+話").unwrap());

/// Returns true if the text contains Chinese characters and no Japanese kana.
/// This handles mixed Chinese/Japanese text by preferring Japanese detection when kana are found.
#[allow(dead_code)]
pub fn is_chinese(text: &str) -> bool {
    if !RE_CHINESE.is_match(text) {
        return false;
    }
    // Exclude Japanese kana (except middle dot ・)
    let has_japanese = text.chars().any(|c| {
        let cp = c as u32;
        (0x3040..=0x30FF).contains(&cp) && cp != 0x30FB
    });
    !has_japanese
}

#[allow(dead_code)]
pub fn is_japanese(text: &str) -> bool {
    RE_JAPANESE.is_match(text)
}

#[allow(dead_code)]
pub fn is_korean(text: &str) -> bool {
    RE_KOREAN.is_match(text)
}

#[allow(dead_code)]
pub fn is_english(text: &str) -> bool {
    RE_ENGLISH.is_match(text)
}

/// Returns the inferred language code from title content.
#[allow(dead_code)]
pub fn get_language_by_title(title: &str) -> &'static str {
    if is_japanese(title) {
        "ja"
    } else if is_korean(title) {
        "ko"
    } else if is_chinese(title) {
        "zh"
    } else {
        "en"
    }
}

/// Returns true if the episode name matches a default pattern (e.g. "Episode 5", "第5集", "第5話")
#[allow(dead_code)]
pub fn is_default_episode_name(name: &str) -> bool {
    RE_DEFAULT_EPISODE_EN.is_match(name)
        || RE_DEFAULT_EPISODE_ZH.is_match(name)
        || RE_DEFAULT_EPISODE_JA.is_match(name)
}

/// Cleans a person name: removes whitespace from CJK names, trims others.
#[allow(dead_code)]
pub fn clean_person_name(name: &str) -> String {
    let trimmed = name.trim();
    if RE_CHINESE.is_match(trimmed) || RE_JAPANESE.is_match(trimmed) || RE_KOREAN.is_match(trimmed)
    {
        // CJK names don't use spaces
        trimmed.chars().filter(|c| !c.is_whitespace()).collect()
    } else {
        trimmed.to_string()
    }
}

/// Cleans an episode name by stripping season/episode numbering patterns after a dot.
#[allow(dead_code)]
pub fn clean_episode_name(name: &str) -> String {
    if let Some(m) = RE_SEASON_EPISODE.find(name) {
        name[..m.start()].to_string()
    } else {
        name.to_string()
    }
}

