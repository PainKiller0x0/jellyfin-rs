/// Convert simplified Chinese to traditional using the embedded mapping table.
/// This is a lightweight approach — covers the most common characters.
#[allow(dead_code)]
pub fn simplified_to_traditional(text: &str) -> String {
    let mut result = String::with_capacity(text.len());
    for ch in text.chars() {
        let converted = S2T_MAP
            .iter()
            .find(|(s, _)| *s == ch)
            .map(|(_, t)| *t)
            .unwrap_or(ch);
        result.push(converted);
    }
    result
}

/// Convert traditional Chinese to simplified (reverse lookup).
#[allow(dead_code)]
pub fn traditional_to_simplified(text: &str) -> String {
    let mut result = String::with_capacity(text.len());
    for ch in text.chars() {
        let converted = S2T_MAP
            .iter()
            .find(|(_, t)| *t == ch)
            .map(|(s, _)| *s)
            .unwrap_or(ch);
        result.push(converted);
    }
    result
}

